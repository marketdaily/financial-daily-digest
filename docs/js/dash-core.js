let currentLang = localStorage.getItem('md-lang-v2') || 'zh';
function T(key) {
  const t = i18n[currentLang] || i18n.zh;
  return t[key] !== undefined ? t[key] : (i18n.zh[key] !== undefined ? i18n.zh[key] : key);
}

function applyLang(lang) {
  currentLang = (lang === 'en') ? 'en' : 'zh';
  const t = i18n[currentLang];
  document.title = t.page_title;
  document.documentElement.lang = currentLang === 'zh' ? 'zh-Hant' : 'en';
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const v = t[el.dataset.i18n];
    if (typeof v === 'string') el.textContent = v;
  });
  document.querySelectorAll('[data-i18n-html]').forEach(el => {
    const v = t[el.dataset.i18nHtml];
    if (typeof v === 'string') el.innerHTML = v;
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const v = t[el.dataset.i18nPlaceholder];
    if (typeof v === 'string') el.placeholder = v;
  });
  const langBtn = document.querySelector('.lang-btn');
  if (langBtn) langBtn.textContent = currentLang === 'zh' ? 'EN' : '中文';
  localStorage.setItem('md-lang-v2', currentLang);
  if (typeof refreshDynamicLang === 'function') refreshDynamicLang();
}

function toggleLang() {
  applyLang(currentLang === 'zh' ? 'en' : 'zh');
}

function togglePwd(inputId, btn) {
  const inp = document.getElementById(inputId);
  if (!inp) return;
  const show = inp.type === "password";
  inp.type = show ? "text" : "password";
  btn.classList.toggle("showing", show);
  btn.setAttribute("aria-label", show ? "隱藏密碼" : "顯示密碼");
}

// Re-render dynamic (JS-set) strings after a language switch
function refreshDynamicLang() {
  const email = localStorage.getItem("md-email");
  const plan = localStorage.getItem("md-plan") || "free";
  if (email && document.getElementById("dashboard").style.display !== "none") {
    const name = email.split("@")[0];
    const heroName = document.getElementById("hero-name");
    if (heroName) heroName.textContent = T('hero_name_greeting')(name);
    const badge = document.getElementById("plan-badge");
    if (badge) badge.textContent = plan === "admin" ? T('hdr_plan_admin') : plan === "free" ? T('hdr_plan_free') : T('hdr_plan_paid');
    renderTags("us"); renderTags("tw"); updateStats();
    if (typeof renderQuickRow === 'function') { renderQuickRow('us'); renderQuickRow('tw'); }
  }
  // push 卡:重跑一次判斷式(未支援/已綁定等狀態)蓋掉 data-i18n 迴圈剛套用的預設文字
  if (typeof setupPushCard === 'function') {
    const pushCard = document.getElementById('push-alert-card');
    if (pushCard && pushCard.style.display !== 'none') setupPushCard(email, plan);
  }
  // alerts feed:項目是語言切換前就已 innerHTML 烘進中文的 DOM,只能強制重抓重繪
  if (typeof loadAlertHistory === 'function' && typeof _alertsLoaded !== 'undefined' && _alertsLoaded) {
    loadAlertHistory(true);
  }
}

